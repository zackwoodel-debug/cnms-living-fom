from .facts import ConsensusEntry, MaterialRecord, Records, SourceRecord, has_properties
from .templates import (
    DensityFact,
    LimitFacts,
    agreement_sentence,
    independence_sentence,
    limit_sentences,
    summary_sentence,
)

#  How each value kind reads in a table: the measured/calculated class first.
KIND_DISPLAY = {
    "literature": "measured (literature or datasheet)",
    "calculated_dft": "calculated (Materials Project DFT)",
    "bulk_approximation": "calculated (bulk value standing in for a film)",
    "calculated_from_lattice": "calculated (from experimental lattice parameters)",
    "calculated_sld": "calculated (periodictable)",
    "calculated_dfpt": "calculated (Materials Project DFPT, 0 K)",
}

LICENCE_LINE = (
    "Data: materials-db, CC BY 4.0. Cite materials-db and the upstream sources "
    "([[Home#Licence and citation|how to cite]])."
)


@dataclass
class Section:
    heading: str
    body: str


@dataclass
class Note:
    note_id: str
    type: str
    title: str
    path: str
    frontmatter: dict
    intro: str
    sections: list[Section]
    #  Prepended to every chunk so it stands alone, and stored on the chunk rows.
    chunk_header: str
    material_id: int | None = None
    family: str | None = None
    formula: str | None = None
    grade: str | None = None
    kind: str | None = None
    aliases: list[str] = field(default_factory=list)
    footer: str = ""


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def link(path: str, text: str | None = None) -> str:
    target = path[:-3] if path.endswith(".md") else path
    if text is None:
        return f"[[{target}]]"
    shown = text.replace("|", "/").replace("[", "(").replace("]", ")")
    return f"[[{target}|{shown}]]"


def cell(text) -> str:
    """A Markdown table cell: pipes escaped, no newlines."""
    if text is None:
        return "—"
    return str(text).replace("\n", " ").replace("|", "\\|")


def code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"``{text}``"


def quote(text: str) -> str:
    """A verbatim release quotation, marked as such."""
    lines = str(text).strip().splitlines() or [""]
    return "\n".join(f"> {line}" for line in lines)


def num(value) -> str:
    return "—" if value is None else fmt_number(value)


_LINK_IN_CELL = re.compile(r"\[\[([^\]|]*?)(?<!\\)\|([^\]]*)\]\]")


def table(header: list[str], rows: list[list[str]]) -> str:
    """A Markdown table. A wikilink's alias pipe is escaped (``[[a\\|b]]``), or it would split the cell."""
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(_LINK_IN_CELL.sub(r"[[\1\\|\2]]", c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def footer(records: Records, note_id: str, extra: str = "") -> str:
    parts = [
        f"materials-db v{records.version}",
        f"sha256 {records.sha256[:12]}",
        code(note_id),
    ]
    if extra:
        parts.append(extra)
    return " · ".join(parts) + "\n\n" + LICENCE_LINE + " Generated by materials-atlas; do not edit."


def _common_fm(records: Records) -> dict:
    return {"release": records.version, "db_sha256": records.sha256}


