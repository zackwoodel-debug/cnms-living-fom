def family_note(records: Records, name: str) -> Note:
    f = records.families[name]
    members = [records.materials[i] for i in f.members]
    fm: dict = {
        "id": f.note_id,
        "type": "family",
        "family": name,
        "materials": len(members),
        "family_table_rows": f.table_rows,
        "manifest_counts": f.manifest_counts,
        "members": [m.note_id for m in members],
        **_common_fm(records),
        "tags": ["family"],
    }
    subject = f"Family {name}"
    counts_rows = [[cell(k), str(v)] for k, v in f.manifest_counts.items()]
    member_lines: list[str] = []
    if name == "glass_catalogs":
        makers: dict[str, list[MaterialRecord]] = {}
        for m in members:
            makers.setdefault(m.name.split()[0], []).append(m)
        for maker in sorted(makers):
            member_lines += ["", f"**{maker}** ({len(makers[maker])})", ""]
            member_lines += [f"- {link(m.path, m.name)}" for m in makers[maker]]
    else:
        member_lines = [f"- {link(m.path, m.name)} ({cell(m.formula) if m.formula else 'no formula'})" for m in members]
    sections = [
        Section(
            "Counts",
            "\n".join(
                [f"{subject}: the MANIFEST's counts for this family, checked against the database at build time.", "", table(["Count", "Value"], counts_rows)]
                + (
                    ["", f"The family table has {f.table_rows} rows; "
                     + ", ".join(f"{cell(n)} (counted under {code(o)})" for n, o in f.counted_elsewhere)
                     + " belong to an earlier family and are counted there."]
                    if f.counted_elsewhere
                    else []
                )
            ),
        ),
        Section("Members", "\n".join([f"{subject} has {len(members)} materials:"] + member_lines)),
    ]
    if f.gaps_not_loaded:
        rows = [
            [cell(g.get("name")), cell(g.get("key") or g.get("selection_key")), cell(g.get("gap_kind")), cell(g.get("reason"))]
            for g in f.gaps_not_loaded
        ]
        sections.append(
            Section(
                "Candidates not in this release",
                "\n".join(
                    [
                        f"{subject}: candidates the release considered and did not load, with its reasons quoted "
                        "from the family's gap list. Not being here is a finding, not an omission.",
                        "",
                        table(["Name", "Key", "Gap kind", "Reason (quoted)"], rows),
                    ]
                ),
            )
        )
    return Note(
        note_id=f.note_id,
        type="family",
        title=f"Family: {name}",
        path=f.path,
        frontmatter=fm,
        intro=f"{subject} of materials-db v{records.version}: {len(members)} materials.",
        sections=sections,
        chunk_header=f"Family: {name} | {f.note_id}",
        family=name,
        kind="family",
        footer=footer(records, f.note_id),
    )


def property_note(records: Records, name: str) -> Note:
    p = records.properties[name]
    fm: dict = {
        "id": p.note_id,
        "type": "property",
        "property": name,
        "unit": p.unit,
        "distribution": p.distribution,
        "materials_with": len(p.materials_with),
        **_common_fm(records),
        "tags": ["property"],
    }
    if p.unit is None:
        del fm["unit"]
    subject = f"Property {p.title}"
    definition = [f"{subject}: what the release's data dictionary says, quoted."]
    for where, text in p.definition:
        definition += ["", f"{code(where)}:", "", quote(text)]
    rubric = {
        "n_633nm": "Graded by rubric 6.1 ([[Methods/Evidence grades]]), one grade per material, phase or variant, and axis.",
        "k_633nm": "Not graded; the release's agreement class is shown with every value.",
        "k_status": "Counted from stored rows (rubric 6.5): k on every row, on some, or on none. A missing k is never 0.",
        "density": "Classified by its stored label (rubric 6.2): " + "; ".join(f"{k}: {v}" for k, v in DENSITY_KIND_NAMES.items()) + ".",
        "xray_sld": "Always calculated (periodictable), never measured.",
        "neutron_sld": "Always calculated (periodictable), never measured.",
        "dielectric": "Always a 0 K Materials Project DFPT calculation, never measured.",
    }[name]
    dist_rows = [[cell(k), str(v)] for k, v in p.distribution.items()]
    with_list = [records.materials[i] for i in p.materials_with]
    sections = [
        Section("Definition", "\n".join(definition)),
        Section("How it is graded", f"{subject}. {rubric}"),
        Section("Distribution", "\n".join([f"{subject}: distribution over this release.", "", table(["Class", "Count"], dist_rows)])),
        Section(
            "Materials with a value",
            f"{subject}: {len(with_list)} materials have a stored value. "
            + (
                f"The list is long: {link(f'Views/{p.title} - materials.md', f'{p.title} - materials')}."
                if len(with_list) > 300
                else "\n\n" + "\n".join(f"- {link(m.path, m.name)}" for m in with_list)
            ),
        ),
    ]
    return Note(
        note_id=p.note_id,
        type="property",
        title=p.title,
        path=p.path,
        frontmatter=fm,
        intro=f"{subject} in materials-db v{records.version}.",
        sections=sections,
        chunk_header=f"Property: {p.title} | {p.note_id}",
        kind="property",
        footer=footer(records, p.note_id),
    )


