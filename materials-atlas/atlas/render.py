def source_note(records: Records, s: SourceRecord) -> Note:
    cited = sorted(s.cited_by)
    by_note = {m.note_id: m for m in records.materials.values()}
    fm: dict = {"id": s.note_id, "type": "source", "source_id": s.source_id}
    for key, value in (
        ("doi", s.doi),
        ("title", s.title),
        ("authors", s.authors),
        ("journal", s.journal),
        ("year", s.year),
        ("technique", s.technique),
        ("url", s.url),
    ):
        if value is not None and value != "":
            fm[key] = value
    fm["author_kind"] = s.parse.kind
    if s.parse.kind == "people":
        fm["authors_parsed"] = [p.label() for p in s.parse.people]
    if s.parse.organisation:
        fm["organisation"] = s.parse.organisation
    fm["citable"] = s.citable
    fm["citable_reason"] = s.citable_reason
    fm["cited_by"] = cited
    fm.update(_common_fm(records))
    fm["tags"] = ["source", f"authors/{s.parse.kind}", "citable" if s.citable else "not-citable"]

    subject = f"Source {s.source_id} ({s.handle})"
    rows = [
        ["Authors", cell(s.authors)],
        ["Title", cell(s.title)],
        ["Journal", cell(s.journal)],
        ["Year", cell(s.year)],
        ["DOI", f"[{s.doi}](https://doi.org/{s.doi})" if s.doi else "—"],
        ["URL", cell(s.url)],
        ["Technique", cell(s.technique)],
    ]
    sections = [
        Section("Citation", "\n".join([f"{subject}, as the release stores it:", "", table(["Field", "Value"], rows), "", f"Citable: **{'yes' if s.citable else 'no'}** ({s.citable_reason})."])),
        Section(
            "What it is cited for",
            f"{subject}. The release's note on this source, quoted:\n\n" + (quote(s.notes) if s.notes else "> (no note)"),
        ),
        Section("Authors as parsed", _authors_section(subject, s)),
        Section(
            "Cited by",
            "\n".join(
                [f"Materials whose datasets or values cite {subject} ({len(cited)}):", ""]
                + [f"- {link(by_note[nid].path, by_note[nid].name)} ({code(nid)})" for nid in cited]
            )
            if cited
            else f"No material in this release cites {subject}.",
        ),
    ]
    return Note(
        note_id=s.note_id,
        type="source",
        title=f"{s.handle}" + (f" — {s.title}" if s.title else ""),
        path=s.path,
        frontmatter=fm,
        intro=f"{subject}: {s.citation()}",
        sections=sections,
        chunk_header=f"Source: {s.handle} | source {s.source_id} | {s.note_id}" + (f" | doi {s.doi}" if s.doi else ""),
        kind="source",
        footer=footer(records, s.note_id),
    )


def _authors_section(subject: str, s: SourceRecord) -> str:
    if s.parse.kind == "people":
        names = ", ".join(f"{p.surname} ({p.initial or 'no initial'})" for p in s.parse.people)
        return (
            f"{subject}: authors read as (surname, first initial) for the independence rubric "
            f"([[Methods/Independence]]): {names}."
        )
    if s.parse.kind == "organisation":
        return f"{subject} is the organisation {s.parse.organisation}, its own author group" + (
            f" ({s.parse.note})." if s.parse.note else "."
        )
    return (
        f"{subject}: no author could be read ({s.parse.note}). Any comparison that relies on this source "
        "has unknown independence."
    )


