"""Records -> notes: frontmatter plus ``##`` sections, held in memory.

The vault writer serialises these notes to Markdown and the index chunks the
same ``Section`` objects, so a note and its chunks cannot drift apart. Every
section's first line names its subject (material name and id, source handle
and id, ...) because a local model may be handed one section alone.

All prose comes from ``templates`` or from fixed labels here; quoted release
text is marked as a quote. Numbers are printed exactly as stored.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
