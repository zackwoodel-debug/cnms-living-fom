def _subject(m: MaterialRecord) -> str:
    return f"{m.name} (id {m.material_id})"


def _source_link(records: Records, sid: int) -> str:
    s = records.sources[sid]
    return link(s.path, s.handle)


def _sources_cell(records: Records, source_ids: list[int]) -> str:
    if not source_ids:
        return "—"
    links = ", ".join(_source_link(records, sid) for sid in source_ids)
    uncitable = [sid for sid in source_ids if not records.sources[sid].citable]
    return links + (" (not citable: " + "; ".join(records.sources[sid].citable_reason for sid in uncitable) + ")" if uncitable else "")


def _entry_fm(e: ConsensusEntry, with_grade: bool) -> dict:
    out: dict = {"scope": e.scope, "property_name": e.property_name}
    if e.value is not None:
        out["value"] = e.value
    out["basis"] = e.basis
    if e.value_origin:
        out["value_origin"] = e.value_origin
    if with_grade and e.grade:
        out["grade"] = e.grade.grade
        out["grade_reason"] = e.grade.reason
    if e.classification:
        out["classification"] = e.classification
        out["voting_datasets"] = e.num_sources
        out["voting_sources"] = len(e.voter_sources)
        out["std_dev"] = e.std_dev
        out["confidence_score"] = e.confidence_score
    if e.groups is not None:
        out["independent_groups"] = independence_value(e.groups)
    if e.contested:
        out["contested_voters"] = [label for label, _ in e.contested]
    return out


def _missing(m: MaterialRecord) -> dict:
    missing: dict[str, str] = {}
    if m.density is None:
        missing["density"] = m.density_evidence.reason
    if not any(e.value is not None for e in m.n633):
        missing["n_633nm"] = "; ".join(sorted({e.grade.reason for e in m.n633 if e.grade})) or "no optical dataset"
    if not any(p.quantity.startswith("dielectric") for p in m.physical):
        missing["dielectric_constant"] = m.dielectric_withheld or "the release stores no dielectric constant for this material"
    if not any(p.quantity.startswith("xray_sld") for p in m.physical):
        missing["sld"] = (
            "no density in this release, so no SLD" if m.density is None else "the release stores no SLD for this material"
        )
    return missing


def material_note(records: Records, m: MaterialRecord) -> Note:
    grades = sorted({e.grade.grade for e in m.n633 if e.grade}, key=lambda g: list(GRADE_RULES).index(g))
    lo, hi = m.wavelength_range
    density = m.density
    has_props = [f"property.{name}" for name in has_properties(m)]

    fm: dict = {"id": m.note_id, "type": "material", "material_id": m.material_id, "key": m.key, "name": m.name}
    if m.formula:
        fm["formula"] = m.formula
    fm["family"] = m.family
    fm["aliases"] = m.aliases
    for key, value in (
        ("cas", m.cas),
        ("pubchem_cid", m.pubchem_cid),
        ("inchikey", m.inchikey),
        ("material_kind", m.material_kind),
        ("material_class", m.material_class),
    ):
        if value is not None:
            fm[key] = value
    if density is not None:
        fm["density_g_cm3"] = density.value
        fm["density_label"] = density.label
        if density.temperature_c is not None:
            fm["density_temperature_c"] = density.temperature_c
        fm["density_source"] = f"source.{density.source_id}"
    fm["density_kind"] = m.density_evidence.kind
    fm["n_633nm"] = [_entry_fm(e, True) for e in m.n633]
    fm["n_633nm_grades"] = grades
    fm["k_633nm"] = [_entry_fm(e, False) for e in m.k633 if e.classification]
    fm["k_status"] = m.k_status
    fm["optical_datasets"] = len(m.datasets)
    fm["measured_datasets"] = sum(d.kind.kind == "measured" for d in m.datasets)
    fm["model_fit_datasets"] = m.n_model_fits
    if lo is not None:
        fm["wavelength_min_nm"] = lo
        fm["wavelength_max_nm"] = hi
    fm["datasets"] = [
        {"id": d.dataset_id, "label": d.label, "kind": d.kind.kind, "k_status": d.k_status, "source": f"source.{d.source_id}", "primary": d.primary}
        for d in m.datasets
    ]
    fm["member_of"] = f"family.{m.family}"
    fm["cites"] = [f"source.{sid}" for sid in m.cites]
    fm["has_property"] = has_props
    fm["missing"] = _missing(m)
    fm.update(_common_fm(records))
    tags = ["material", f"family/{m.family}"] + [f"grade/{g}" for g in grades] + [f"k/{m.k_status}", f"density/{m.density_evidence.kind}"]
    if m.family == "glass_catalogs":
        tags.append(f"maker/{m.name.split()[0]}")
    fm["tags"] = tags

    s = _subject(m)
    sections = [
        Section("Summary", _summary(records, m)),
        Section("Evidence at a glance", _evidence(records, m)),
        Section("Identity", _identity(records, m)),
        Section("Optical datasets", _datasets(records, m)),
        Section("Physical properties", _physical(records, m)),
        Section("Agreement between sources", _agreement(records, m)),
        Section("Flags and gaps", _flags(records, m)),
        Section("What this note cannot tell you", _limits(m)),
        Section("Get the data", _get_data(records, m)),
    ]
    intro = (
        f"Reference record for {s}, stable key {code(m.key)}, in "
        f"{link(records.families[m.family].path, m.family)}. Values are materials-db v{records.version} "
        "reference data, shown exactly as stored."
    )
    #  The quantities this material holds, in the words a question uses ("refractive
    #  index", not n_633nm), so a section matches the question even when it only shows
    #  a symbol. Facts about the record, not prose about the material.
    words = {
        "n_633nm": "refractive index n",
        "k_633nm": "extinction coefficient k",
        "density": "density",
        "xray_sld": "X-ray scattering length density",
        "neutron_sld": "neutron scattering length density",
        "dielectric": "dielectric constant (permittivity)",
    }
    holds = [words[name] for name in has_properties(m) if name in words]
    if m.datasets:
        holds.insert(0, "optical constants n and k against wavelength")
    header = " | ".join(
        x
        for x in (
            f"Material: {m.name}",
            f"formula {m.formula}" if m.formula else "no formula",
            f"id {m.material_id}",
            m.note_id,
            f"key {m.key}",
            ("also known as: " + ", ".join(m.aliases)) if m.aliases else "",
            ("holds: " + ", ".join(holds)) if holds else "",
        )
        if x
    )
    return Note(
        note_id=m.note_id,
        type="material",
        title=m.name,
        path=m.path,
        frontmatter=fm,
        intro=intro,
        sections=sections,
        chunk_header=header,
        material_id=m.material_id,
        family=m.family,
        formula=m.formula,
        grade=",".join(grades),
        kind=m.material_kind,
        aliases=m.aliases,
        footer=footer(records, m.note_id, f"material_id {m.material_id}"),
    )


def _summary(records: Records, m: MaterialRecord) -> str:
    lo, hi = m.wavelength_range
    density = (
        DensityFact(m.density.value, m.density.label, m.density_evidence.kind) if m.density is not None else None
    )
    lines = [
        summary_sentence(
            name=m.name,
            formula=m.formula,
            material_id=m.material_id,
            n_datasets=len(m.datasets),
            wavelength_min_nm=lo,
            wavelength_max_nm=hi,
            n_model_fits=m.n_model_fits,
            density=density,
            density_absent_reason=m.density_evidence.reason if m.density is None else None,
        )
    ]
    for e in m.n633:
        prefix = f"n at 633 nm ({e.scope}): " if len(m.n633) > 1 else ""
        sentence = agreement_sentence(
            grade=e.grade.grade if e.grade else "none",
            consensus_class=e.classification,
            n_voting=e.num_sources or 0,
            n_sources=len(e.voter_sources),
            n_model_fits=len(e.model_fits),
            n_other_temperature=len(e.other_temperatures),
        )
        extra = independence_sentence(e.groups)
        lines.append(prefix + sentence + (f" {extra}" if extra else ""))
    return "\n\n".join(lines)


def _evidence(records: Records, m: MaterialRecord) -> str:
    rows = []
    for e in m.n633:
        sources = _sources_cell(records, e.voter_sources)
        value = num(e.value) if e.value is not None else "no stored value"
        rows.append(
            [
                "n at 633 nm",
                cell(e.scope),
                value,
                f"**{e.grade.grade}**" if e.grade else "—",
                cell(e.basis.replace("_", " ")),
                sources,
                cell(e.classification),
                cell(independence_value(e.groups) if e.groups is not None else None),
            ]
        )
    for e in m.k633:
        if not e.classification:
            continue
        rows.append(
            [
                "k at 633 nm",
                cell(e.scope),
                num(e.value),
                "—",
                "consensus",
                _sources_cell(records, e.voter_sources),
                cell(e.classification),
                cell(independence_value(e.groups) if e.groups is not None else None),
            ]
        )
    if m.density is not None:
        rows.append(
            [
                "density (g/cm3)",
                cell(m.density.phase),
                num(m.density.value),
                cell(KIND_DISPLAY[m.density_evidence.kind]),
                cell(m.density.label),
                _sources_cell(records, [m.density.source_id]),
                "—",
                "—",
            ]
        )
    else:
        rows.append(["density", "—", "not in this release", "absent", "—", "—", "—", "—"])
    rows.append(["k status", "all datasets", cell(m.k_status), "—", "counted from stored rows", "—", "—", "—"])
    body = [
        f"Evidence for {_subject(m)}: each value with its grade or kind, where it comes from, and how far its sources agree.",
        "",
        table(["Quantity", "Scope", "Value (as stored)", "Grade / kind", "Basis", "Sources", "Agreement", "Independent groups"], rows),
        "",
        "Why each grade (rubric in [[Methods/Evidence grades]]):",
    ]
    for e in m.n633:
        body.append(f"- n at 633 nm, {e.scope}: **{e.grade.grade}**: {e.grade.reason}.")
    body.append(f"- Density: {m.density_evidence.kind}: {m.density_evidence.reason}.")
    return "\n".join(body)


def _identity(records: Records, m: MaterialRecord) -> str:
    rows = [
        ["Name", cell(m.name)],
        ["Formula", cell(m.formula) if m.formula else "no formula in this release (product or mixture)"],
        ["Stable key", code(m.key)],
        ["material_id", str(m.material_id)],
        ["Atlas id", code(m.note_id)],
        ["Phase named in the key", cell(m.key.split("@", 1)[1]) if "@" in m.key else "none"],
        ["CAS", cell(m.cas)],
        ["PubChem CID", cell(m.pubchem_cid)],
        ["InChIKey", cell(m.inchikey)],
        ["SMILES", code(m.smiles) if m.smiles else "—"],
        ["Molecular weight (PubChem, g/mol)", num(m.molecular_weight)],
        ["Material kind / class", cell(" / ".join(x for x in (m.material_kind, m.material_class) if x) or None)],
        ["Also known as", cell(", ".join(m.aliases) or None)],
    ]
    tables = sorted({f for f, _ in m.family_rows})
    lines = [
        f"Identity of {_subject(m)}. A formula is not an identity: this record is the material named here, "
        "and other materials may share its formula.",
        "",
        table(["Field", "Value"], rows),
    ]
    if len(tables) > 1:
        lines += [
            "",
            f"Listed in the family tables {', '.join(code(t) for t in tables)}; the release counts it once, under "
            f"{code(m.family)}.",
        ]
    return "\n".join(lines)


def _datasets(records: Records, m: MaterialRecord) -> str:
    if not m.datasets:
        return f"{_subject(m)} has no optical dataset in this release."
    rows = []
    for d in m.datasets:
        rows.append(
            [
                code(d.label).replace("|", "\\|"),
                _source_link(records, d.source_id),
                f"{num(d.wavelength_min_nm)}-{num(d.wavelength_max_nm)}",
                str(d.n_rows),
                num(d.temperature_c) if d.temperature_c is not None else "not stated",
                d.kind.kind.replace("_", " "),
                d.k_status.replace("_", " "),
                "primary" if d.primary else "",
            ]
        )
    lines = [
        f"{_subject(m)} has {len(m.datasets)} optical dataset{'s' if len(m.datasets) != 1 else ''}. "
        "A dataset is one source, one phase or variant, one axis and one temperature; datasets are never merged.",
        "",
        table(["Dataset label", "Source", "Range (nm)", "Points", "Temperature (degC)", "Kind", "k", "Primary"], rows),
    ]
    fits = [d for d in m.datasets if d.kind.kind == "model_fit"]
    if fits:
        lines += ["", "Model fits, with the evidence materials-db's dataset_kind.py quotes:"]
        lines += [f"- {code(d.label)}: “{d.kind.reason}”" for d in fits]
    covering = [d for d in m.datasets if d.bracket_633]
    if covering:
        lines += ["", "Stored rows at or either side of 633 nm (exact stored values; the atlas does not interpolate):"]
        for d in covering:
            points = "; ".join(
                f"{num(wl)} nm: n = {num(n)}" + (f", k = {num(k)}" if k is not None else ", k not given")
                for wl, n, k in d.bracket_633
            )
            lines.append(f"- {code(d.label)}: {points}")
    notes = [d for d in m.datasets if d.temperature_note]
    if notes:
        lines += ["", "Temperature notices (release inconsistencies, reported, not corrected):"]
        lines += [f"- {code(d.label)}: {d.temperature_note}." for d in notes]
    return "\n".join(lines)


def _physical(records: Records, m: MaterialRecord) -> str:
    if not m.physical:
        return f"{_subject(m)} has no density, SLD or dielectric value in this release."
    rows = []
    for p in m.physical:
        conditions = []
        if p.temperature_c is not None:
            conditions.append(f"{num(p.temperature_c)} degC")
        if p.frequency_hz is not None:
            conditions.append(f"{num(p.frequency_hz)} Hz")
        if p.wavelength_nm is not None:
            conditions.append(f"radiation {num(p.wavelength_nm)} nm")
        if p.energy_ev is not None:
            conditions.append(f"{num(p.energy_ev)} eV")
        rows.append(
            [
                cell(p.quantity),
                num(p.value),
                cell(p.unit or "dimensionless"),
                code(p.label).replace("|", "\\|"),
                cell(KIND_DISPLAY[p.kind.kind]),
                cell(", ".join(conditions) or None),
                _source_link(records, p.source_id),
                "yes" if records.sources[p.source_id].citable else cell("no: " + records.sources[p.source_id].citable_reason),
            ]
        )
    return "\n".join(
        [
            f"Physical properties of {_subject(m)}, exactly as stored, each with its kind (measured or calculated).",
            "",
            table(["Quantity", "Value", "Unit", "Label", "Kind", "Conditions", "Source", "Citable"], rows),
        ]
    )


def _agreement(records: Records, m: MaterialRecord) -> str:
    lines = [f"How far the sources for {_subject(m)} agree, from the release's own comparisons."]
    consensus = [e for e in [*m.n633, *m.k633] if e.classification]
    if consensus:
        rows = []
        for e in consensus:
            groups = "—"
            if e.groups is not None:
                if e.groups.status == "determined":
                    groups = f"{e.groups.n_groups}: " + "; ".join(
                        "+".join(records.sources[sid].handle for sid in comp) for comp in e.groups.components
                    )
                else:
                    groups = f"unknown ({e.groups.reason})"
            rows.append(
                [
                    code(e.property_name).replace("|", "\\|"),
                    num(e.value),
                    num(e.std_dev),
                    str(e.num_sources),
                    cell(", ".join(e.voters)),
                    cell(e.classification),
                    num(e.confidence_score),
                    cell(groups),
                ]
            )
        lines += [
            "",
            "Consensus at 633 nm (median of measured ambient datasets; model fits never vote):",
            "",
            table(["Property", "Value", "Std dev", "Voting datasets", "Which", "Class", "Confidence", "Author groups"], rows),
        ]
        for e in consensus:
            for label, t in e.contested:
                lines.append(
                    f"\n**Warning:** the release counted {code(label)} as ambient because its rows store no temperature, "
                    f"but its label names {fmt_number(t)} degC. The stored {code(e.property_name)} mixes temperatures."
                )
    else:
        lines += ["", "No consensus row: fewer than one measured ambient dataset covers 633 nm, or none at all."]
    if m.validations:
        rows = [
            [
                v.property_name,
                code(v.dataset_a).replace("|", "\\|"),
                code(v.dataset_b).replace("|", "\\|"),
                f"{v.classification} ({v.relation.replace('_', ' ')})",
                num(v.mean_relative_error),
                num(v.rmse),
                num(v.pearson_r),
                cell(v.notes),
            ]
            for v in m.validations
        ]
        lines += [
            "",
            "Dataset comparisons over the wavelengths both cover (dataset_validation):",
            "",
            table(["Property", "Dataset A", "Dataset B", "Class", "Mean rel. error", "RMSE", "Pearson r", "Notes (quoted)"], rows),
        ]
    return "\n".join(lines)


def _flags(records: Records, m: MaterialRecord) -> str:
    lines = [f"What the release's build tables record about {_subject(m)}: choices, evidence and gaps, quoted verbatim."]
    for family, row in sorted(m.family_rows, key=lambda x: x[0]):
        if row.get("flags"):
            lines += ["", f"From {code(f'family_tables/{family}.csv')} `flags`:", "", quote(row["flags"])]
    for family, row in m.gaps:
        reason = row.get("reason") or ""
        lines += [
            "",
            f"From the {code(family)} gap list (gap kind {code(row.get('gap_kind') or '—')}):",
            "",
            quote(reason + (f" Evidence: {row['evidence']}" if row.get("evidence") else "")),
        ]
    if m.notices:
        lines += ["", "Found by the atlas (release inconsistencies, reported, not corrected):"]
        lines += [f"- {text}" for text in m.notices]
    if len(lines) == 1:
        lines += ["", "No flags or gap entries are recorded for this material."]
    return "\n".join(lines)


def _limits(m: MaterialRecord) -> str:
    voters = {label for e in m.n633 for label in e.voters}
    facts = LimitFacts(
        k_status=m.k_status,
        density_kind=m.density_evidence.kind,
        density_absent_reason=m.density_evidence.reason if m.density is None else None,
        has_sld=any(p.quantity.startswith(("xray_sld", "neutron_sld")) for p in m.physical),
        has_dielectric=any(p.quantity.startswith("dielectric") for p in m.physical),
        n_model_fits=m.n_model_fits,
        unstated_temperature_labels=[d.label for d in m.datasets if d.label in voters and d.temperature_c is None],
        phase_unstated=m.phase_unstated,
        dielectric_withheld_reason=m.dielectric_withheld,
    )
    return "\n".join([f"Limits of the record for {_subject(m)}:", ""] + [f"- {s}" for s in limit_sentences(facts)])


def _get_data(records: Records, m: MaterialRecord) -> str:
    first = m.datasets[0].label if m.datasets else None
    sql = [
        f"-- materials-db v{records.version}; open read-only: sqlite3 'file:materials-db-v{records.version}.sqlite?mode=ro'",
        f"SELECT * FROM physical_properties WHERE material_id = {m.material_id};",
        f"SELECT * FROM consensus_properties WHERE material_id = {m.material_id};",
    ]
    py = [
        "from materials_db.access.db import ReleaseDB",
        f'db = ReleaseDB("~/code/materials-db/release/materials-db-v{records.version}")',
        f"db.material({m.material_id})",
    ]
    if first is not None:
        escaped = first.replace("'", "''")
        sql.insert(
            1,
            "SELECT wavelength_nm, n, k, temperature_c FROM optical_dispersion\n"
            f"  WHERE material_id = {m.material_id} AND dataset_label = '{escaped}'\n  ORDER BY wavelength_nm;",
        )
        py.append(f"db.optical({m.material_id}, dataset_label={first!r})")
        py.append(f"db.nk_at({m.material_id}, 633, all_datasets=True)  # the release's own interpolation")
    return "\n".join(
        [
            f"How to read the stored rows of {_subject(m)} directly (every dataset label is listed under Optical datasets).",
            "",
            "```sql",
            *sql,
            "```",
            "",
            "```python",
            *py,
            "```",
        ]
    )


